/**
 * Spec-to-test traceability gate.
 *
 *   tsx scripts/check-traceability.ts            # verify; exit 1 on any gap
 *   tsx scripts/check-traceability.ts --write    # also regenerate specs/TRACE.md
 *
 * A requirement is a bold `**REQ-AREA-NNN**` in specs/*.md. A test "covers" it by mentioning the ID
 * anywhere in tests/. Two failures: a requirement nobody tests, and a test that cites an ID no spec
 * defines (a typo, or a deleted requirement).
 *
 * .maestro/ flows are scanned too (typos are caught) and listed in TRACE.md, but they do NOT count as
 * coverage: they only run on an emulator in CI, not in the fast suite this gate belongs to.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOT = process.cwd();
const REQ_ID = /REQ-[A-Z]+-\d{3}/g;
const REQ_DEFINITION = /\*\*(REQ-[A-Z]+-\d{3})\*\*\s+(.*)/;
const SPEC_DIR = 'specs';
const TEST_DIR = 'tests';
const E2E_DIR = '.maestro';
const TEST_FILE = /\.test\.tsx?$/;
const E2E_FILE = /\.ya?ml$/;

function walk(dir: string): string[] {
  let entries: string[];
  try {
    entries = readdirSync(dir);
  } catch {
    return [];
  }
  return entries.flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const requirements = new Map<string, string>();
for (const file of walk(join(ROOT, SPEC_DIR)).filter((f) => f.endsWith('.md') && !f.endsWith('TRACE.md'))) {
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const match = REQ_DEFINITION.exec(line);
    if (match?.[1]) requirements.set(match[1], (match[2] ?? '').trim());
  }
}

const coverage = new Map<string, Set<string>>();
const e2eCoverage = new Map<string, Set<string>>();
const unknownCitations: string[] = [];
const scan = (dir: string, pattern: RegExp, into: Map<string, Set<string>>) => {
  for (const file of walk(join(ROOT, dir)).filter((f) => pattern.test(f))) {
    const rel = relative(ROOT, file);
    for (const id of new Set(readFileSync(file, 'utf8').match(REQ_ID) ?? [])) {
      if (!requirements.has(id)) {
        unknownCitations.push(`${rel} cites ${id}, which no spec defines`);
        continue;
      }
      into.set(id, (into.get(id) ?? new Set()).add(rel));
    }
  }
};
scan(TEST_DIR, TEST_FILE, coverage);
scan(E2E_DIR, E2E_FILE, e2eCoverage);

const untested = [...requirements.keys()].filter((id) => !coverage.has(id)).sort();

if (process.argv.includes('--write')) {
  const cell = (files?: Set<string>) =>
    [...(files ?? [])].sort().map((f) => `\`${f}\``).join('<br>');
  const rows = [...requirements.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, text]) => `| ${id} | ${text} | ${cell(coverage.get(id)) || '**NONE**'} | ${cell(e2eCoverage.get(id))} |`);
  writeFileSync(
    join(ROOT, SPEC_DIR, 'TRACE.md'),
    [
      '# Traceability matrix (generated by `npm run trace:write`)',
      '',
      '"Proven by" lists tests that run in the fast suite. "E2E flows" are Maestro flows that run only on an emulator in CI; they are listed for navigation and are not counted as proof by the gate.',
      '',
      '| Requirement | Text | Proven by | E2E flows |',
      '|---|---|---|---|',
      ...rows,
      '',
    ].join('\n'),
  );
}

console.log(`requirements: ${requirements.size}, covered: ${requirements.size - untested.length}`);
for (const id of untested) console.error(`UNTESTED  ${id}  ${requirements.get(id)}`);
for (const message of unknownCitations) console.error(`UNKNOWN   ${message}`);
process.exit(untested.length > 0 || unknownCitations.length > 0 ? 1 : 0);
